ORIGINAL_LIST=[]
for i in range(1,11):
    ORIGINAL_LIST.append(i)
print(f"ORIGINAL LIST: {ORIGINAL_LIST}") 
EXTRACTED_ELEMENTS=list(ORIGINAL_LIST[0:5])
print(f"EXTRACTED FIRST FIVE ELEMENT IS: {EXTRACTED_ELEMENTS}")
REVERSE_ELEMENT=list(EXTRACTED_ELEMENTS[::-1])
print(f"REVERSED EXTRACTED ELEMENTS IS: {REVERSE_ELEMENT}")   